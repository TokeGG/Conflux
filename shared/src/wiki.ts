// The generated wiki (WIKI.md) and the credits text. Both are plain text built from the data, so a test can keep the committed
// wiki honest: it must equal what this produces.
import type { AugmentDef, GameData, SkillDef } from './types.ts';

const code = (s: string) => `\`${s}\``;
const num = (n: number) => String(Math.round(n * 1000) / 1000);
const list = (xs: readonly string[]) => (xs.length ? xs.join(', ') : '-');
const cell = (s: string) => s.replace(/\|/g, '\\|');

function table(head: string[], rows: string[][]): string {
  const out = [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`];
  for (const r of rows) out.push(`| ${r.map(cell).join(' | ')} |`);
  return out.join('\n');
}

const params = (p: Record<string, number>) =>
  Object.entries(p)
    .map(([k, v]) => `${k} ${num(v)}`)
    .join(', ') || '-';

function shape(s: SkillDef): string {
  const { type, ...rest } = s.shape;
  const bits = Object.entries(rest).map(([k, v]) => `${k} ${typeof v === 'number' ? num(v) : v}`);
  return bits.length ? `${type} (${bits.join(', ')})` : type;
}

function augmentValues(a: AugmentDef): string {
  const rarities = (['common', 'rare', 'epic'] as const).map((r) => `${r}: ${Object.entries(a.rarity[r]).map(([k, v]) => `${k} ${num(v)}`).join(', ') || '-'}`);
  return rarities.join('; ');
}

const augmentTarget = (a: AugmentDef) => Object.entries(a.target).map(([k, v]) => `${k} ${v}`).join(', ');

/** The whole wiki as Markdown. Byte-for-byte the same for the same data. */
export function genWiki(data: GameData): string {
  const out: string[] = ['# Conflux wiki', '', '_Generated by `npm run wiki` from the game data. Do not edit by hand._', ''];

  out.push('## Elements', '');
  out.push(`Ten elements; three are held at a time on keys 1 to 3. Every pair of elements has a reaction (see Reactions). Weakness and resistance multiply damage by x${num(data.elements.multipliers.weak)} and x${num(data.elements.multipliers.resist)}.`, '');
  out.push(
    table(
      ['Element', 'Hits leave', 'Reacts to', 'Weak to', 'Resists'],
      data.elements.order.map((el) => [el, data.elements.status[el] ?? '-', data.elements.reacts[el], list(data.elements.cycle[el].weak), list(data.elements.cycle[el].resist)]),
    ),
    '',
  );

  out.push('## Skills', '');
  out.push(
    table(
      ['Skill', 'Element', 'Slot', 'Shape', 'Damage', 'Cooldown', 'Applies', 'Tags'],
      Object.values(data.skills).map((s) => [code(s.id), s.element, s.slot, shape(s), num(s.damage), `${num(s.cooldown)} s`, s.applies ?? '-', list(s.tags)]),
    ),
    '',
  );

  out.push('## Augments', '');
  out.push(
    table(
      ['Augment', 'Name', 'Kind', 'Target', 'Values'],
      Object.values(data.augments).map((a) => [code(a.id), a.name, a.kind, augmentTarget(a), augmentValues(a)]),
    ),
    '',
  );

  out.push('## Statuses', '');
  out.push(
    table(
      ['Status', 'Duration', 'Effect'],
      Object.entries(data.statuses).map(([id, s]) => {
        const fx: string[] = [];
        if (s.tickDamage) fx.push(`${num(s.tickDamage)} damage every ${num(s.tickInterval ?? 1)} s`);
        if (s.spreadRadius) fx.push(`spreads within ${num(s.spreadRadius)} m`);
        if (s.speedMul !== undefined) fx.push(`speed x${num(s.speedMul)}`);
        if (s.damageTakenMul !== undefined) fx.push(`damage taken x${num(s.damageTakenMul)}`);
        if (s.damageDealtMul !== undefined) fx.push(`damage dealt x${num(s.damageDealtMul)}`);
        if (s.maxStacks) fx.push(`stacks up to ${num(s.maxStacks)}`);
        if (s.canAct === false) fx.push('cannot act');
        return [code(id), `${num(s.duration)} s`, list(fx)];
      }),
    ),
    '',
  );

  out.push('## Reactions', '');
  out.push(`One reaction for every pair of elements. It fires when a target carrying one element's status is hit by the other, in either order. Reactions of the same enemy wait ${num(data.reactionCooldown)} s between triggers.`, '');
  out.push(table(['Reaction', 'Elements', 'Effect', 'Numbers'], data.reactions.map((r) => [code(r.id), `${r.pair[0]} + ${r.pair[1]}`, r.effect, params(r.params)])), '');

  out.push('## Enemies', '');
  out.push(
    table(
      ['Enemy', 'Name', 'Element', 'Health', 'Speed', 'Cost', 'AI', 'Weak to', 'Resists', 'Immune to', 'Attacks'],
      Object.values(data.enemies).map((e) => [code(e.id), e.name, e.element, num(e.hp), num(e.speed), num(e.cost), e.ai, list(e.weak), list(e.resist), list(e.immune ?? []), list(e.attacks)]),
    ),
    '',
  );

  out.push('## Elite modifiers', '');
  out.push(table(['Modifier', 'Name', 'Numbers'], Object.values(data.elites).map((m) => [code(m.id), m.name, params(m.params)])), '');

  out.push('## Unlocks', '');
  out.push(
    table(
      ['Achievement', 'Name', 'Needs', 'Unlocks'],
      Object.values(data.unlocks).map((u) => [code(u.id), u.name, `${u.counter} >= ${u.atLeast}`, list([...(u.unlocks.skills ?? []), ...(u.unlocks.augments ?? [])].map(code))]),
    ),
    '',
  );

  return out.join('\n');
}

export interface LicenseEntry {
  path: string;
  title: string;
  author: string;
  license: string;
  verified: boolean;
  source: string;
  note?: string;
}

/** The credits: every asset whose licence asks for attribution, as "Title by Author (licence), link". */
export function genCredits(entries: LicenseEntry[]): string {
  const credited = entries.filter((e) => e.license.startsWith('CC-BY')).sort((a, b) => a.title.localeCompare(b.title) || a.path.localeCompare(b.path));
  return credited.map((e) => `${e.title} by ${e.author} (${e.license}), ${e.source}`).join('\n');
}
